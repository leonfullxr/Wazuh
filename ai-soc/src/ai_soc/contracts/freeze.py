def as_dict(value: object) -> dict[str, object]:
    return cast(dict[str, object], value) if isinstance(value, dict) else {}


def as_list(value: object) -> list[object]:
    return cast(list[object], value) if isinstance(value, list) else []


def as_string(value: object) -> str:
    return value if isinstance(value, str) else ""


def canonical_json(value: object) -> bytes:
    return json.dumps(
        value, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False
    ).encode("utf-8")


def pretty_json(value: object) -> bytes:
    return (
        json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2, allow_nan=False) + "\n"
    ).encode("utf-8")


def digest(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def file_digest(path: Path) -> str:
    hasher = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            hasher.update(chunk)
    return hasher.hexdigest()


def all_models() -> list[type[BaseModel]]:
    found: list[type[BaseModel]] = []
    for value in vars(models).values():
        if isinstance(value, type) and value is not StrictModel and issubclass(value, StrictModel):
            found.append(value)
    return sorted(found, key=lambda model: model.__name__)


def model_schema_bundle() -> dict[str, object]:
    definitions: dict[str, object] = {}
    for model in all_models():
        schema = cast(dict[str, object], model.model_json_schema(ref_template="#/$defs/{model}"))
        nested = as_dict(schema.pop("$defs", {}))
        for name, nested_schema in nested.items():
            definitions.setdefault(name, nested_schema)
        definitions[model.__name__] = schema
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://ai-soc.invalid/contracts/v1/models.schema.json",
        "title": "AI SOC v1 contract models",
        "freeze_revision": "1.15",
        "$defs": definitions,
    }


def ts_type(value: object) -> str:
    schema = as_dict(value)
    ref = schema.get("$ref")
    if isinstance(ref, str):
        return ref.rsplit("/", 1)[-1]
    union = schema.get("anyOf", schema.get("oneOf"))
    if union is not None:
        return " | ".join(sorted({ts_type(choice) for choice in as_list(union)}))
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(item, ensure_ascii=False) for item in as_list(schema["enum"]))
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema.get('items'))}>"
    if kind == "object":
        properties = as_dict(schema.get("properties"))
        if properties:
            required = {as_string(item) for item in as_list(schema.get("required"))}
            fields: list[str] = []
            for name, field_schema in sorted(properties.items()):
                marker = "" if name in required else "?"
                fields.append(f"  {json.dumps(name)}{marker}: {ts_type(field_schema)};")
            return "{\n" + "\n".join(fields) + "\n}"
        additional = schema.get("additionalProperties")
        return (
            f"{{ [key: string]: {ts_type(additional)} }}"
            if additional is not None
            else "Record<string, never>"
        )
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(as_string(kind), "unknown")


def openapi_refs(value: object) -> object:
    if isinstance(value, dict):
        source = cast(dict[str, object], value)
        converted: dict[str, object] = {}
        for key, item in source.items():
            if key == "$ref" and isinstance(item, str) and item.startswith("#/$defs/"):
                converted[key] = item.replace("#/$defs/", "#/components/schemas/", 1)
            else:
                converted[key] = openapi_refs(item)
        return converted
    if isinstance(value, list):
        return [openapi_refs(item) for item in cast(list[object], value)]
    return value


def typescript(bundle: dict[str, object]) -> bytes:
    lines = [
        "// Generated by ai_soc.contracts.freeze; do not edit by hand.",
        "// Freeze revision 1.15.",
        "",
    ]
    for name, model_schema in sorted(as_dict(bundle["$defs"]).items()):
        body = ts_type(model_schema)
        if body.startswith("{\n"):
            lines.extend([f"export interface {name} {body}", ""])
        else:
            lines.extend([f"export type {name} = {body};", ""])
    return "\n".join(lines).encode("utf-8")


