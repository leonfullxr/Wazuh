def fixture_digest() -> str:
    hasher = hashlib.sha256()
    for path in sorted(item for item in FIXTURES.rglob("*") if item.is_file()):
        relative = path.relative_to(FIXTURES).as_posix().encode("utf-8")
        payload = path.read_bytes()
        hasher.update(len(relative).to_bytes(4, "big"))
        hasher.update(relative)
        hasher.update(len(payload).to_bytes(8, "big"))
        hasher.update(payload)
    return hasher.hexdigest()


def registries() -> tuple[list[str], list[str]]:
    traceability = as_dict(json.loads((ROOT / "docs/traceability.json").read_text("utf-8")))
    case_catalog = as_dict(json.loads((ROOT / "docs/case_catalog.json").read_text("utf-8")))
    contract_cases = as_dict(
        json.loads((ROOT / "tests/fixtures/v1/contract_cases.json").read_text("utf-8"))
    )
    acceptances = sorted(
        {
            as_string(as_dict(row).get("acceptance_id"))
            for row in as_list(traceability.get("entries"))
        }
        - {""}
    )
    catalog_case_ids = {
        as_string(as_dict(row).get("case_id")) for row in as_list(case_catalog.get("cases"))
    }
    contract_case_ids = {
        as_string(as_dict(row).get("case_id")) for row in as_list(contract_cases.get("cases"))
    }
    case_ids = sorted((catalog_case_ids | contract_case_ids) - {""})
    return acceptances, case_ids


def fixture_bindings_hash() -> str:
    catalog = json.loads((ROOT / "docs" / "case_catalog.json").read_text("utf-8"))
    return case_fixture_bindings_sha256(catalog)


def artifacts() -> dict[Path, bytes]:
    schema = model_schema_bundle()
    schema_bytes = pretty_json(schema)
    openapi_bytes = pretty_json(openapi(schema))
    ts_bytes = typescript(schema)
    runner = as_dict(json.loads((CONTRACTS / "runner-manifest.json").read_text("utf-8")))
    acceptances, cases = registries()
    port_hash = digest((ROOT / "src/ai_soc/contracts/ports.py").read_bytes())
    manifest: dict[str, object] = {
        "contract_version": "1",
        "freeze_revision": "1.15",
        "schema_sha256": digest(schema_bytes),
        "openapi_sha256": digest(openapi_bytes),
        "typescript_sha256": digest(ts_bytes),
        "fixture_tree_sha256": fixture_digest(),
        "case_fixture_bindings_sha256": fixture_bindings_hash(),
        "fixture_mode_required": True,
        "port_signature_sha256": port_hash,
        "python_import_path": "ai_soc",
        "python_version": runner.get("python", "unrecorded"),
        "typescript_generation_version": "ai_soc.contracts.freeze/1.15",
        "supported_mcp_revision": "2025-11-25",
        "acceptance_ids": acceptances,
        "case_ids": cases,
        "runner_manifest_sha256": digest(pretty_json(runner)),
    }
    return {
        CONTRACTS / "models.schema.json": schema_bytes,
        CONTRACTS / "openapi.json": openapi_bytes,
        CONTRACTS / "generated/types.ts": ts_bytes,
        CONTRACTS / "freeze.json": pretty_json(manifest),
    }


def check_typescript() -> None:
    runner = as_dict(json.loads((CONTRACTS / "runner-manifest.json").read_text("utf-8")))
    node_path = as_string(runner.get("node_executable"))
    npm_path = as_string(runner.get("npm_executable"))
    compiler_path = as_string(runner.get("typescript_compiler"))
    archive_path = as_string(runner.get("node_archive_path"))
    checksums_path = as_string(runner.get("node_checksum_manifest_path"))
    arguments = [as_string(value) for value in as_list(runner.get("typescript_check_arguments"))]
    if not all((node_path, npm_path, compiler_path, archive_path, checksums_path, *arguments)):
        raise SystemExit("runner manifest lacks pinned JavaScript tool/cache identities")
    files = {
        name: (ROOT / value).resolve()
        for name, value in (
            ("Node", node_path),
            ("npm", npm_path),
            ("TypeScript", compiler_path),
            ("Node archive", archive_path),
            ("Node checksum manifest", checksums_path),
            ("TypeScript lock", "contracts/v1/tooling/package-lock.json"),
        )
    }
    for name, path in files.items():
        if not path.is_relative_to(ROOT):
            raise SystemExit(
                f"runner manifest {name} path must stay inside the repository checkout"
            )
        if not path.is_file():
            raise SystemExit(f"pinned {name} artifact is missing: {path.relative_to(ROOT)}")
    node = files["Node"]
    npm = files["npm"]
    compiler = files["TypeScript"]
    archive = files["Node archive"]
    checksums = files["Node checksum manifest"]
    lock = files["TypeScript lock"]
    if hashlib.sha256(archive.read_bytes()).hexdigest() != runner.get("node_archive_sha256"):
        raise SystemExit("pinned Node archive hash mismatch")
    if hashlib.sha256(checksums.read_bytes()).hexdigest() != runner.get(
        "node_checksum_manifest_sha256"
    ):
        raise SystemExit("pinned Node checksum manifest hash mismatch")
    if hashlib.sha256(lock.read_bytes()).hexdigest() != runner.get(
        "typescript_package_lock_sha256"
    ):
        raise SystemExit("pinned TypeScript package lock hash mismatch")
    checksum_entries = checksums.read_text("utf-8").splitlines()
    expected_archive_digest = as_string(runner.get("node_archive_sha256"))
    if not any(
        line.split(maxsplit=1) == [expected_archive_digest, as_string(runner.get("node_archive"))]
        for line in checksum_entries
    ):
        raise SystemExit("pinned Node archive does not match the official checksum manifest")
    expected_node = "v" + as_string(runner.get("node"))
    expected_npm = as_string(runner.get("npm"))
    expected_typescript = "Version " + as_string(runner.get("typescript"))
    for command, expected, label in (
        ([str(node), "--version"], expected_node, "Node"),
        ([str(npm), "--version"], expected_npm, "npm"),
        ([str(node), str(compiler), "--version"], expected_typescript, "TypeScript"),
    ):
        try:
            result = subprocess.run(
                command, cwd=ROOT, check=False, capture_output=True, text=True, timeout=30
            )
        except (OSError, subprocess.TimeoutExpired) as error:
            raise SystemExit(f"pinned {label} tool unavailable: {error}") from error
        if result.returncode != 0 or result.stdout.strip() != expected:
            raise SystemExit(
                f"pinned {label} version mismatch: expected {expected!r}; "
                f"got {result.stdout.strip()!r}"
            )
    try:
        result = subprocess.run(
            [str(node), str(compiler), *arguments],
            cwd=ROOT,
            check=False,
            capture_output=True,
            text=True,
            timeout=60,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        raise SystemExit(f"pinned TypeScript compile could not run: {error}") from error
    if result.returncode != 0:
        raise SystemExit(
            "generated TypeScript failed strict compilation:\n" + result.stdout + result.stderr
        )


def check_browser_preparation() -> None:
    runner = as_dict(json.loads((CONTRACTS / "runner-manifest.json").read_text("utf-8")))
    artifact_specs = (
        ("Browser preparation lock", "browser_prep_lock_path", "browser_prep_lock_sha256"),
        ("UI package lock", "b5_ui_lock_cache_path", "b5_ui_lock_sha256_reported"),
        (
            "UI package manifest",
            "b5_ui_package_json_cache_path",
            "b5_ui_package_json_sha256",
        ),
        ("Chromium", "chromium_executable", "chromium_sha256"),
        (
            "Chromium headless shell",
            "chromium_headless_shell_executable",
            "chromium_headless_shell_sha256",
        ),
    )
    artifacts: dict[str, Path] = {}
    for name, path_key, hash_key in artifact_specs:
        relative = as_string(runner.get(path_key))
        expected_hash = as_string(runner.get(hash_key))
        path = (ROOT / relative).resolve()
        if not relative or not path.is_relative_to(ROOT):
            raise SystemExit(
                f"runner manifest {name} path must stay inside the repository checkout"
            )
        if not path.is_file():
            raise SystemExit(f"pinned {name} artifact is missing: {relative}")
        if not expected_hash or file_digest(path) != expected_hash:
            raise SystemExit(f"pinned {name} artifact hash mismatch")
        artifacts[name] = path

    lock = as_dict(json.loads(artifacts["Browser preparation lock"].read_text("utf-8")))
    packages = as_dict(lock.get("packages"))
    expected_packages = {
        "node_modules/@axe-core/playwright": "4.13.0",
        "node_modules/@playwright/test": "1.63.0",
        "node_modules/@types/node": "22.20.5",
        "node_modules/typescript": as_string(runner.get("typescript")),
        "node_modules/vite": as_string(runner.get("vite")),
    }
    for package, version in expected_packages.items():
        if as_string(as_dict(packages.get(package)).get("version")) != version:
            raise SystemExit(f"browser preparation lock has wrong {package} version")

    b5_lock = as_dict(json.loads(artifacts["UI package lock"].read_text("utf-8")))
    b5_packages = as_dict(b5_lock.get("packages"))
    expected_b5_packages = {
        "node_modules/@axe-core/playwright": "4.13.0",
        "node_modules/@playwright/test": "1.63.0",
        "node_modules/@types/node": "22.20.5",
        "node_modules/playwright-core": "1.63.0",
        "node_modules/typescript": as_string(runner.get("typescript")),
        "node_modules/vite": as_string(runner.get("vite")),
    }
    for package, version in expected_b5_packages.items():
        if as_string(as_dict(b5_packages.get(package)).get("version")) != version:
            raise SystemExit(f"UI package lock has wrong {package} version")
    b5_browsers_path = (
        ROOT
        / as_string(runner.get("b5_ui_install_cache"))
        / "node_modules/playwright-core/browsers.json"
    ).resolve()
    if not b5_browsers_path.is_relative_to(ROOT) or not b5_browsers_path.is_file():
        raise SystemExit("Playwright browser metadata is missing from the prepared cache")
    browser_metadata = as_dict(json.loads(b5_browsers_path.read_text("utf-8")))
    browser_rows = as_list(browser_metadata.get("browsers"))
    for browser_name in ("chromium", "chromium-headless-shell"):
        matches = [as_dict(row) for row in browser_rows if as_dict(row).get("name") == browser_name]
        if len(matches) != 1:
            raise SystemExit(f"Playwright metadata lacks unique {browser_name} pin")
        row = matches[0]
        if row.get("revision") != runner.get("browser_revision") or row.get(
            "browserVersion"
        ) != runner.get("browser_version"):
            raise SystemExit(f"Playwright metadata has wrong {browser_name} pin")

    expected_browser = "Google Chrome for Testing " + as_string(runner.get("browser_version"))
    for name in ("Chromium", "Chromium headless shell"):
        try:
            result = subprocess.run(
                [str(artifacts[name]), "--version"],
                cwd=ROOT,
                check=False,
                capture_output=True,
                text=True,
                timeout=30,
            )
        except (OSError, subprocess.TimeoutExpired) as error:
            raise SystemExit(f"pinned {name} binary unavailable: {error}") from error
        if result.returncode != 0 or result.stdout.strip() != expected_browser:
            raise SystemExit(
                f"pinned {name} version mismatch: expected {expected_browser!r}; "
                f"got {result.stdout.strip()!r}"
            )


def check_platform_preparation() -> None:
    runner = as_dict(json.loads((CONTRACTS / "runner-manifest.json").read_text("utf-8")))
    artifact_specs = (
        ("Terraform archive", "terraform_archive", "terraform_archive_sha256"),
        ("Terraform executable", "terraform_executable", "terraform_executable_sha256"),
        ("TFLint archive", "tflint_archive", "tflint_archive_sha256"),
        ("TFLint executable", "tflint_executable", "tflint_executable_sha256"),
        ("Trivy archive", "trivy_archive", "trivy_archive_sha256"),
        ("Trivy executable", "trivy_executable", "trivy_executable_sha256"),
        ("Docker Compose executable", "docker_compose_executable", "docker_compose_archive_sha256"),
        ("Docker Buildx executable", "docker_buildx_executable", "docker_buildx_archive_sha256"),
        ("platform toolchain lock", "b6_toolchain_lock_cache_path", "b6_toolchain_lock_sha256"),
        ("provider lock", "provider_lock_cache_path", "provider_lock_sha256"),
        ("Trivy database", "scan_database_cache_path", "scan_database_content_sha256"),
    )
    artifacts: dict[str, Path] = {}
    for name, path_key, hash_key in artifact_specs:
        relative = as_string(runner.get(path_key))
        expected_hash = as_string(runner.get(hash_key))
        path = (ROOT / relative).resolve()
        if not relative or not path.is_relative_to(ROOT):
            raise SystemExit(
                f"runner manifest {name} path must stay inside the repository checkout"
            )
        if not path.is_file():
            raise SystemExit(f"pinned {name} artifact is missing: {relative}")
        if not expected_hash or file_digest(path) != expected_hash:
            raise SystemExit(f"pinned {name} artifact hash mismatch")
        artifacts[name] = path

    toolchain = as_dict(json.loads(artifacts["platform toolchain lock"].read_text("utf-8")))
    locked_images = {
        as_string(as_dict(row).get("name")): as_dict(row)
        for row in as_list(toolchain.get("images"))
    }
    manifest_images = [as_dict(row) for row in as_list(runner.get("images"))]
    manifest_names = [as_string(row.get("name")) for row in manifest_images]
    if not manifest_names or len(manifest_names) != len(set(manifest_names)):
        raise SystemExit("runner manifest image names must be nonempty and unique")
    if set(manifest_names) != set(locked_images):
        raise SystemExit(
            "runner manifest image set differs from the committed platform toolchain lock"
        )
    for image in manifest_images:
        name = as_string(image.get("name"))
        locked = locked_images[name]
        if image.get("reference") != locked.get("reference"):
            raise SystemExit(
                f"runner manifest image reference differs from the pinned toolchain: {name}"
            )
        if image.get("prepared") is not False:
            raise SystemExit(
                f"image preparation is incomplete and must remain marked unprepared: {name}"
            )
        for key in ("version", "commit", "index_digest", "platform_manifest_sha256"):
            if key in locked and image.get(key) != locked.get(key):
                raise SystemExit(
                    f"runner manifest image {key} differs from the pinned toolchain: {name}"
                )

    tool_checks = (
        (
            "Terraform",
            "terraform_executable",
            ["version"],
            "Terraform v" + as_string(runner.get("terraform")),
        ),
        (
            "TFLint",
            "tflint_executable",
            ["--version"],
            "TFLint version " + as_string(runner.get("tflint")),
        ),
        (
            "Trivy",
            "trivy_executable",
            ["--version"],
            "Version: " + as_string(runner.get("trivy")),
        ),
        (
            "Docker Compose",
            "docker_compose_executable",
            ["--version"],
            "Docker Compose version " + as_string(runner.get("docker_compose")),
        ),
        (
            "Docker Buildx",
            "docker_buildx_executable",
            ["version"],
            "github.com/docker/buildx "
            + as_string(runner.get("docker_buildx"))
            + " "
            + as_string(runner.get("docker_buildx_commit")),
        ),
    )
    for label, path_key, args, expected_prefix in tool_checks:
        relative = as_string(runner.get(path_key))
        try:
            result = subprocess.run(
                [str((ROOT / relative).resolve()), *args],
                cwd=ROOT,
                check=False,
                capture_output=True,
                text=True,
                timeout=30,
            )
        except (OSError, subprocess.TimeoutExpired) as error:
            raise SystemExit(f"pinned {label} executable unavailable: {error}") from error
        if result.returncode != 0 or not result.stdout.strip().startswith(expected_prefix):
            raise SystemExit(
                f"pinned {label} version mismatch: expected prefix {expected_prefix!r}; "
                f"got {result.stdout.strip()!r}"
            )


def generate(check: bool) -> None:
    failures: list[str] = []
    for path, expected in artifacts().items():
        if check:
            if not path.exists() or path.read_bytes() != expected:
                failures.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected)
    if failures:
        raise SystemExit("contract freeze drift: " + ", ".join(failures))
    check_typescript()
    check_browser_preparation()
    check_platform_preparation()


def main() -> None:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    options = parser.parse_args()
    generate(check=options.check)
    print("CF-1 artifacts verified" if options.check else "CF-1 artifacts generated")


if __name__ == "__main__":
    main()
