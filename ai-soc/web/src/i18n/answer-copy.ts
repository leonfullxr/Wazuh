export function removedFindingsCopy(count: number, locale: Locale) {
    const key = count === 1 ? "findingRemovedOne" : "findingRemovedMany";
    return words[locale][key].replace("{count}", String(count));
}
export function fmt(locale: Locale, key: keyof typeof words.en) {
    return words[locale][key];
}
export function localeEnum<T extends string>(
    map: Record<T, [string, string]>,
    value: T,
    locale: Locale,
) {
    return map[value][locale === "en" ? 0 : 1];
}
